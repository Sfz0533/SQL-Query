## QUESTION 10

Classify customers based on their total sales.

High Value   = Sales >= 80,000
Medium Value = Sales >= 40,000
Low Value    = Sales < 40,000

SOLUTION:

WITH CustomerSales AS
(
SELECT
c.CustomerID,
c.CustomerName,
SUM(od.Quantity * p.Price) AS TotalSales
FROM Customers c
JOIN Orders o
ON c.CustomerID = o.CustomerID
JOIN OrderDetails od
ON o.OrderID = od.OrderID
JOIN Products p
ON od.ProductID = p.ProductID
WHERE o.Status = 'Completed'
GROUP BY
c.CustomerID,
c.CustomerName
)
SELECT
CustomerName,
TotalSales,

```
CASE
    WHEN TotalSales >= 80000 THEN 'High Value'
    WHEN TotalSales >= 40000 THEN 'Medium Value'
    ELSE 'Low Value'
END AS CustomerCategory
```

FROM CustomerSales;

