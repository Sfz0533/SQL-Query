## QUESTION 17

Find customers who purchased both Laptop and Smartphone.

SOLUTION:

SELECT
c.CustomerName
FROM Customers c
JOIN Orders o
ON c.CustomerID = o.CustomerID
JOIN OrderDetails od
ON o.OrderID = od.OrderID
JOIN Products p
ON od.ProductID = p.ProductID
