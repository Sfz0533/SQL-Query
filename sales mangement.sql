## QUESTION 12

Calculate the running total of sales.

SOLUTION:

WITH DailySales AS
(
SELECT
o.OrderDate,
SUM(od.Quantity * p.Price) AS DailySales
FROM Orders o
JOIN OrderDetails od
ON o.OrderID = od.OrderID
JOIN Products p
ON od.ProductID = p.ProductID
WHERE o.Status = 'Completed'
GROUP BY o.OrderDate
)
SELECT
OrderDate,
DailySales,

```
SUM(DailySales) OVER
(
    ORDER BY OrderDate
    ROWS BETWEEN UNBOUNDED PRECEDING
    AND CURRENT ROW
) AS RunningTotal
```

FROM DailySales
ORDER BY OrderDate;

## QUESTION 13

Find the previous day's sales using LAG().

SOLUTION:

WITH DailySales AS
(
SELECT
o.OrderDate,
SUM(od.Quantity * p.Price) AS DailySales
FROM Orders o
JOIN OrderDetails od
ON o.OrderID = od.OrderID
JOIN Products p
ON od.ProductID = p.ProductID
WHERE o.Status = 'Completed'
GROUP BY o.OrderDate
)
SELECT
OrderDate,
DailySales,

```
LAG(DailySales) OVER
(
    ORDER BY OrderDate
) AS PreviousDaySales
```

FROM DailySales;

## QUESTION 14

Find the sales difference between the current day and previous day.

SOLUTION:

WITH DailySales AS
(
SELECT
o.OrderDate,
SUM(od.Quantity * p.Price) AS DailySales
FROM Orders o
JOIN OrderDetails od
ON o.OrderID = od.OrderID
JOIN Products p
ON od.ProductID = p.ProductID
WHERE o.Status = 'Completed'
GROUP BY o.OrderDate
),
SalesComparison AS
(
SELECT
OrderDate,
DailySales,
LAG(DailySales) OVER
(
ORDER BY OrderDate
) AS PreviousDaySales
FROM DailySales
)
SELECT
OrderDate,
DailySales,
PreviousDaySales,
DailySales - PreviousDaySales AS SalesDifference
FROM SalesComparison;

