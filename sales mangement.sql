## QUESTION 1

Find the total sales generated by each customer.

SOLUTION:

SELECT
c.CustomerID,
c.CustomerName,
SUM(od.Quantity * p.Price) AS TotalSales
FROM Customers c
JOIN Orders o
ON c.CustomerID = o.CustomerID
JOIN OrderDetails od
ON o.OrderID = od.OrderID
JOIN Products p
ON od.ProductID = p.ProductID
WHERE o.Status = 'Completed'
GROUP BY
c.CustomerID,
c.CustomerName
ORDER BY TotalSales DESC;

## QUESTION 2

Find customers whose total sales are greater than 50,000.

SOLUTION:

SELECT
c.CustomerName,
SUM(od.Quantity * p.Price) AS TotalSales
FROM Customers c
JOIN Orders o
ON c.CustomerID = o.CustomerID
JOIN OrderDetails od
ON o.OrderID = od.OrderID
JOIN Products p
ON od.ProductID = p.ProductID
WHERE o.Status = 'Completed'
GROUP BY c.CustomerName
HAVING SUM(od.Quantity * p.Price) > 50000;

## QUESTION 3

Find the top 3 customers based on total sales.

SOLUTION:

SELECT TOP 3
c.CustomerName,
SUM(od.Quantity * p.Price) AS TotalSales
